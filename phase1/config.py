"""
Все калибруемые пороги в одном месте.
Крутить здесь, не по коду. Единицы подписаны в комментариях.

Phase 1: значения выставлены разумно "на глаз". Настоящая калибровка —
на синтетике и потом на реальном вокале. Ничего тут не захардкожено вслепую
по коду: если число влияет на результат, оно здесь.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class Config:
    # --- временнáя сетка ---
    frame_ms: float = 10.0          # длительность одного фрейма, мс

    # --- пороги интонации (центы) ---
    # доля времени внутри ±T идёт в p25/p50/p100
    thr_tight: float = 25.0         # центы
    thr_main: float = 50.0          # центы — ГЛАВНЫЙ порог (p50)
    thr_loose: float = 100.0        # центы

    # --- маски ---
    transition_ms: float = 45.0     # ±окно вокруг границы ноты, исключается из intonation
    #   ВНИМАНИЕ: калибруемый порог. На быстрых пассажах 45 мс могут съесть
    #   короткие ноты — в Phase 2+ привязать к темпу, пока фиксирован.

    # --- сегментация нот (для note-level агрегации) ---
    note_min_ms: float = 90.0       # короче — это глиссандо/украшение, не нота
    note_coverage_min: float = 0.60 # доля длительности ноты, которую надо спеть, чтобы она считалась "покрытой"

    # --- вибрато ---
    vibrato_rate_hz: tuple = (4.0, 8.0)   # типичный диапазон частоты вибрато
    vibrato_min_extent_cents: float = 20.0 # размах меньше — не вибрато, просто дрожь

    # --- октава ---
    octave_tol_cents: float = 50.0  # |error| в пределах 1200±этого → флаг OCTAVE

    # --- confidence gate ---
    gate: float = 0.5               # ниже — показываем LOW CONFIDENCE, число скрыто
    coverage_min_for_score: float = 0.30  # если спето меньше — оценивать нечего

    # --- note verdict ---
    note_correct_cents: float = 50.0  # |медиана отклонения ноты| ≤ этого → correct

    # --- worst mistakes ---
    worst_top_n: int = 5


CFG = Config()