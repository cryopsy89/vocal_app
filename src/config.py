"""
Все калибруемые пороги в одном месте.
Крутить здесь, не по коду. Единицы подписаны в комментариях.

Phase 1: значения выставлены разумно "на глаз". Настоящая калибровка —
на синтетике и потом на реальном вокале. Ничего тут не захардкожено вслепую
по коду: если число влияет на результат, оно здесь.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class Config:
    # --- временнáя сетка ---
    frame_ms: float = 10.0          # длительность одного фрейма, мс

    # --- пороги интонации (центы) ---
    # доля времени внутри ±T идёт в p25/p50/p100
    thr_tight: float = 25.0         # центы
    thr_main: float = 50.0          # центы — ГЛАВНЫЙ порог (p50)
    thr_loose: float = 100.0        # центы

    # --- маски ---
    transition_ms: float = 45.0     # ±окно вокруг границы ноты, исключается из intonation
    #   ВНИМАНИЕ: калибруемый порог. На быстрых пассажах 45 мс могут съесть
    #   короткие ноты — в Phase 2+ привязать к темпу, пока фиксирован.

    # --- сегментация нот (для note-level агрегации) ---
    note_min_ms: float = 90.0       # короче — это глиссандо/украшение, не нота
    note_coverage_min: float = 0.60 # доля длительности ноты, которую надо спеть, чтобы она считалась "покрытой"
    smooth_ms: float = 200.0        # окно медианного сглаживания перед сегментацией;
    #   >= периода вибрато (5-6 Гц => ~170-200мс), иначе вибрато дробит ноты
    note_change_semitones: float = 1.0  # порог смены ноты (полутона); смена
    #   подтверждается только если новый уровень держится >= note_min_ms
    outlier_from_median: float = 9.0   # отскок > этого от ГЛОБАЛЬНОЙ медианы песни +
    #   короткий пробег = игла-артефакт. 9 полутонов: реальный вокальный диапазон
    #   фразы ~±7пт от медианы, артефакты (октавные срывы) — 12-31пт. Порог между.
    outlier_max_run_ms: float = 120.0  # И короче этого = игла. Реальный высокий/низкий
    #   заход голоса держится дольше, поэтому не режется

    # --- вибрато ---
    vibrato_rate_hz: tuple = (4.0, 8.0)   # типичный диапазон частоты вибрато
    vibrato_min_extent_cents: float = 20.0 # размах меньше — не вибрато, просто дрожь
    vibrato_max_extent_cents: float = 250.0 # размах больше — это переход/глиссандо, не вибрато

    # --- октава ---
    octave_tol_cents: float = 50.0  # |error| в пределах 1200±этого → флаг OCTAVE

    # --- транспоз (определение тональности/октавы дубля) ---
    transpose_max: int = 24         # макс. сдвиг ключа (полутоны), ±2 октавы
    transpose_search_semitones: int = 7  # радиус перебора вокруг грубой оценки
    transpose_min_conf: float = 0.05  # ниже — авто не уверено, просим ручной ключ

    # --- confidence gate ---
    gate: float = 0.5               # ниже — показываем LOW CONFIDENCE, число скрыто
    coverage_min_for_score: float = 0.30  # если спето меньше — оценивать нечего
    min_scored_ms: float = 500.0    # если в счёт попало меньше — оценивать не на чем,
    #   LOW CONFIDENCE (закрывает ложные 100% на пустом/почти пустом входе)

    # --- note verdict ---
    note_correct_cents: float = 50.0  # |медиана отклонения ноты| ≤ этого → correct

    # --- DTW alignment ---
    dtw_band_ms: float = 700.0      # макс. рассинхрон, который DTW имеет право убрать.
    #   АБСОЛЮТНЫЙ, не доля длины: иначе на длинном фрагменте DTW уходит на секунды
    #   и МАСКИРУЕТ систематический pitch-сдвиг, пересопоставляя чужие ноты.
    dtw_unvoiced_penalty: float = 4.0  # штраф voiced-vs-unvoiced в матрице стоимостей

    # --- worst mistakes ---
    worst_top_n: int = 5


CFG = Config()
